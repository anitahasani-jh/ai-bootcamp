# ==========================================
# Arithmetic Operators in Python
# عملگرهای ریاضی در پایتون
# ==========================================
x = 10
y = 3

# Addition (+) — جمع
print("Addition:", x + y)

# Subtraction (-) — تفریق
print("Subtraction:", x - y)

# Multiplication (*) — ضرب
print("Multiplication:", x * y)

# Division (/) — تقسیم
print("Division:", x / y)

# Floor Division (//) — تقسیم صحیح
print("Floor Division:", x // y)

# Modulus (%) — باقی‌مانده
print("Modulus:", x % y)

# Exponentiation (**) — توان
print("Exponentiation:", x ** y)